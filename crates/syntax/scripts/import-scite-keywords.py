#!/usr/bin/env python3
"""Writes src/keywords.rs from the keyword lists in SciTE's .properties files.

SciTE (https://www.scintilla.org/SciTE.html) shares Scintilla's permissive
license. Usage, from crates/syntax:

    scripts/import-scite-keywords.py /path/to/scite/src > src/keywords.rs

Each language below names a sample file; its keyword lists are the ones
SciTE uses for that file: `keywords.<patterns>` for list 0,
`keywords2.<patterns>` for list 1, and so on.
"""

import fnmatch
import pathlib
import re
import sys

# OxyPad language name -> a file SciTE would open with its keywords.
SAMPLES = {
    "bash": "x.sh",
    "batch": "x.bat",
    "c": "x.c",
    "cmake": "CMakeLists.txt",
    "cpp": "x.cpp",
    "csharp": "x.cs",
    "css": "x.css",
    "go": "x.go",
    "html": "x.html",
    "java": "x.java",
    "javascript": "x.js",
    "json": "x.json",
    "lua": "x.lua",
    "perl": "x.pl",
    "php": "x.php",
    "powershell": "x.ps1",
    "python": "x.py",
    "ruby": "x.rb",
    "rust": "x.rs",
    "sql": "x.sql",
    "swift": "x.swift",
    "xml": "x.xml",
    "yaml": "x.yaml",
}

MAX_LISTS = 9


def read_properties(directory: pathlib.Path) -> dict[str, str]:
    properties: dict[str, str] = {}
    for path in sorted(directory.glob("*.properties")):
        pending = ""
        for raw in path.read_text(encoding="latin-1").splitlines():
            line = pending + raw.strip()
            pending = ""
            if line.endswith("\\"):
                pending = line[:-1] + " "
                continue
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            properties[key.strip()] = value.strip()
    return properties


def expand(text: str, properties: dict[str, str], depth: int = 0) -> str:
    if depth > 20:
        return text
    return re.sub(
        r"\$\(([^)]+)\)",
        lambda match: expand(properties.get(match.group(1), ""), properties, depth + 1),
        text,
    )


def keyword_lists(properties: dict[str, str], sample: str) -> list[str]:
    lists = [""] * MAX_LISTS
    for key, value in properties.items():
        match = re.fullmatch(r"keywords(\d*)\.(.+)", key)
        if not match:
            continue
        index = int(match.group(1) or "1") - 1
        if not 0 <= index < MAX_LISTS:
            continue
        patterns = expand(match.group(2), properties).split(";")
        if any(fnmatch.fnmatch(sample, pattern.strip()) for pattern in patterns if pattern.strip()):
            words = " ".join(expand(value, properties).split())
            lists[index] = words
    while lists and not lists[-1]:
        lists.pop()
    return lists


def main() -> None:
    properties = read_properties(pathlib.Path(sys.argv[1]))
    print("//! Keyword lists from SciTE's .properties files, which share Scintilla's")
    print("//! license. Generated by scripts/import-scite-keywords.py; do not edit.")
    print()
    for language, sample in sorted(SAMPLES.items()):
        lists = keyword_lists(properties, sample)
        print(f"pub const {language.upper()}: &[&str] = &[")
        for words in lists:
            escaped = words.replace("\\", "\\\\").replace('"', '\\"')
            print(f'    "{escaped}",')
        print("];")
        print()


if __name__ == "__main__":
    main()
